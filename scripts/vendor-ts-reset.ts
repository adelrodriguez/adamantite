/**
 * Re-vendors the ts-reset declarations that the `adamantite/typescript` preset loads.
 *
 * The npm registry has ts-reset 0.6.1, but the upstream repository has later fixes. The script
 * copies the declaration files of the entry points below, and each file that they reference, at a
 * pinned commit. The preset lists the entry points in `files`, so a target project installs
 * nothing.
 *
 * Usage: node scripts/vendor-ts-reset.ts
 *
 * After you change the pinned ref, review the upstream diff of `src/entrypoints`, and run the
 * TypeScript preset tests.
 */
import { execFile } from "node:child_process"
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import path from "node:path"
import { promisify } from "node:util"

const execFileAsync = promisify(execFile)

const REPO_URL = "https://github.com/total-typescript/ts-reset"

// The "Version Packages" commit of 0.7.0, which upstream has not published to npm.
const PINNED_REF = "f36610ba441b8ea1c7cf7349dd71bee26c2e6a3b"

const SOURCE_DIR = "src/entrypoints"

// The recommended set, and the storage reset that upstream ships only in its `dom` entry point.
const ENTRY_POINTS = ["recommended.d.ts", "storage.d.ts"]

const OUT_DIR = path.join(import.meta.dirname, "..", "presets", "typescript", "vendor", "ts-reset")

const REFERENCE_PATTERN = /^\/\/\/ <reference path="(?<file>[^"]+)" \/>$/gmu

async function run(command: string, args: string[], cwd: string) {
  return execFileAsync(command, args, { cwd })
}

function readReferences(content: string) {
  return [...content.matchAll(REFERENCE_PATTERN)].flatMap((match) => match.groups?.file ?? [])
}

/**
 * Reads the given files and every file that they reference, keyed by file name.
 */
async function readDeclarations(
  sourceDir: string,
  files: readonly string[],
  declarations: ReadonlyMap<string, string> = new Map()
): Promise<ReadonlyMap<string, string>> {
  const unread = [...new Set(files)].filter((file) => !declarations.has(file))

  if (unread.length === 0) {
    return declarations
  }

  const read = await Promise.all(
    unread.map(async (file) => [file, await readFile(path.join(sourceDir, file), "utf8")] as const)
  )

  return readDeclarations(
    sourceDir,
    read.flatMap(([, content]) => readReferences(content)),
    new Map([...declarations, ...read])
  )
}

const cloneDir = await mkdtemp(path.join(tmpdir(), "ts-reset-"))

try {
  await run("git", ["clone", `${REPO_URL}.git`, "."], cloneDir)
  await run("git", ["checkout", PINNED_REF], cloneDir)

  const declarations = await readDeclarations(path.join(cloneDir, SOURCE_DIR), ENTRY_POINTS)
  const upstreamLicense = await readFile(path.join(cloneDir, "LICENSE"), "utf8")

  const banner = `// Vendored from ts-reset (${REPO_URL}, MIT) at commit ${PINNED_REF}.
// See license.md for the full license text.
//
// Generated by scripts/vendor-ts-reset.ts — do not edit by hand.

`

  // Remove the earlier copy, so a file that upstream no longer references does not stay behind.
  await rm(OUT_DIR, { force: true, recursive: true })
  await mkdir(OUT_DIR, { recursive: true })

  await Promise.all(
    [...declarations].map(([file, content]) =>
      writeFile(path.join(OUT_DIR, file), banner + content)
    )
  )

  await writeFile(
    path.join(OUT_DIR, "license.md"),
    `# ts-reset license

The declaration files in this folder are copies of
[ts-reset](${REPO_URL}) at commit ${PINNED_REF}.

${upstreamLicense}`
  )

  console.info(`Vendored ${declarations.size} ts-reset declarations at ${PINNED_REF} to ${OUT_DIR}`)
} finally {
  // Keep a cleanup failure from masking the clone or copy error.
  await rm(cloneDir, { force: true, recursive: true }).catch(() => null)
}
